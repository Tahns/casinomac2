#!/usr/bin/env node
// WP11: pack a SMALL set of real v2 books into frontend_mambo/fixtures/ (mock RGS, unit and e2e tests). Zero dependencies.
//   node tools/build/make_fixtures.mjs [--src <math fixtures_out dir>] [--per 3]
// Source: math/games/agent_mambo/library/fixtures_out (written by the math's own tools/make_fixtures_v2.py from the FINAL published
// books, after recompression). This tool never re-simulates and never edits math/: it keeps at most --per ids of every category of
// the math PICKS.md (plus enough books for every category the mock RGS can force: loss, win, bigwin, bonus, retrigger, maxwin),
// copies those books byte for byte, and writes
//   fixtures/index.json                    the four modes and their cost (identical to the published index.json)
//   fixtures/books_<mode>_sample.jsonl     the kept books (SDK form: payoutMultiplier and amounts are integers in 1/100 x)
//   fixtures/lookUpTable_<mode>_0.csv      the published lookup rows of exactly those books (id, weight, payout x100)
//   fixtures/PICKS.md                      kept ids per category (the bracket still gives the count in the whole mode)
//   fixtures/SOURCE.json                   sha256 of every source file and every written file
// The v1 fixtures (books of the shipped v1 math, no layout / mission events) stay in fixtures/v1/ for the v1 identity suites.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const FRONT = path.resolve(HERE, '../..');
const ROOT = path.resolve(FRONT, '..');
const arg = (k, d) => { const i = process.argv.indexOf(k); return i >= 0 ? process.argv[i + 1] : d; };
const SRC = path.resolve(arg('--src', path.join(ROOT, 'math/games/agent_mambo/library/fixtures_out')));
const PUB = path.join(ROOT, 'math/games/agent_mambo/library/publish_files');
const OUT = path.join(FRONT, 'fixtures');
const PER = Number(arg('--per', 3));
const MOCK_MIN = 2; // books per mock category
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

const index = JSON.parse(fs.readFileSync(path.join(SRC, 'index.json'), 'utf8'));
const pubIndex = fs.existsSync(path.join(PUB, 'index.json')) ? JSON.parse(fs.readFileSync(path.join(PUB, 'index.json'), 'utf8')) : null;
if (pubIndex && JSON.stringify(pubIndex) !== JSON.stringify(index)) throw new Error('fixtures_out/index.json differs from publish_files/index.json: re-run the math fixtures');

// ---- PICKS.md of the math: ## mode / - **cat** [N in the mode] (desc): ids
function readPicks(file) {
  const out = {}; let mode = null;
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const h = /^##\s+(\w+)/.exec(line); if (h) { mode = h[1]; out[mode] = []; continue; }
    const m = /^- \*\*(\w+)\*\*\s*\[(\d+) in the mode\]\s*\((.*)\):\s*([\d,\s]*)$/.exec(line);
    if (m && mode) out[mode].push({ cat: m[1], total: Number(m[2]), desc: m[3], ids: m[4].split(',').map((s) => s.trim()).filter(Boolean).map(Number).filter(Number.isInteger) });
  }
  return out;
}
const picks = readPicks(path.join(SRC, 'PICKS.md'));

// the mock RGS categories (tools/mock-rgs/server.mjs `category`)
const hasEv = (b, t) => b.events.some((e) => e.type === t);
function mockCat(b) {
  const p = Number(b.payoutMultiplier || 0);
  if (hasEv(b, 'wincap') || p >= 500000) return 'maxwin';
  if (hasEv(b, 'freeSpinRetrigger')) return 'retrigger';
  if (hasEv(b, 'freeSpinTrigger')) return 'bonus';
  if (p >= 1500) return 'bigwin';
  return p > 0 ? 'win' : 'loss';
}

fs.mkdirSync(OUT, { recursive: true });
const source = { generated: new Date().toISOString(), src: path.relative(ROOT, SRC), per: PER, files: {}, written: {} };
let picksMd = '# Book ids per category (v2 FINAL math; books_<mode>_sample.jsonl: payoutMultiplier and amounts are integers in 1/100 x of the play amount)\n\n'
  + 'Generated by `node tools/build/make_fixtures.mjs` from `math/games/agent_mambo/library/fixtures_out` (the math\'s own pick of the FINAL\n'
  + `published books). At most ${PER} ids per category are kept; the bracket is the number of books of the whole mode in that category.\n`
  + '`bonus` books are the v1 books (no `missionAssigned`, no `layout`): they play as The Briefing, step 8, Mezzanine. Doors never carry a `layout`.\n'
  + 'The v1 fixtures of the shipped v1 math are kept in `fixtures/v1/`.\n';
const summary = [];
for (const m of index.modes) {
  const mode = m.name;
  const srcBooks = path.join(SRC, `books_${mode}_sample.jsonl`);
  const lines = fs.readFileSync(srcBooks, 'utf8').split('\n').filter(Boolean);
  source.files[`books_${mode}_sample.jsonl`] = sha(fs.readFileSync(srcBooks));
  const byId = new Map(lines.map((l) => { const b = JSON.parse(l); return [b.id, { b, line: l }]; }));
  const keep = new Set();
  const cats = picks[mode] || [];
  picksMd += `\n## ${mode}\n`;
  for (const c of cats) {
    const ids = c.ids.filter((id) => byId.has(id)).slice(0, PER);
    ids.forEach((id) => keep.add(id));
    picksMd += `- **${c.cat}** [${c.total} in the mode] (${c.desc}): ${ids.join(', ')}\n`;
  }
  // every category the mock can force: top up from the source sample
  const need = {};
  for (const id of keep) { const k = mockCat(byId.get(id).b); need[k] = (need[k] || 0) + 1; }
  for (const [id, { b }] of byId) { const k = mockCat(b); if ((need[k] || 0) < MOCK_MIN) { keep.add(id); need[k] = (need[k] || 0) + 1; } }
  // guideline [273] needs base wins of at most 0.3x (sub-cent payouts at the smallest play amount)
  if (mode === 'base') { let n = [...keep].filter((id) => { const p = byId.get(id).b.payoutMultiplier; return p > 0 && p <= 30; }).length; for (const [id, { b }] of byId) { if (n >= MOCK_MIN) break; if (b.payoutMultiplier > 0 && b.payoutMultiplier <= 30 && !keep.has(id)) { keep.add(id); n++; } } }
  // ids ascending, but the SHORTEST book first: the mock RGS serves list[0] for a replay of an unknown event id (guideline replay checks)
  const kept = [...keep].sort((a, b) => a - b);
  const shortest = kept.reduce((best, id) => (byId.get(id).b.events.length < byId.get(best).b.events.length ? id : best), kept[0]);
  kept.splice(kept.indexOf(shortest), 1); kept.unshift(shortest);
  const outBooks = kept.map((id) => byId.get(id).line).join('\n') + '\n';
  fs.writeFileSync(path.join(OUT, `books_${mode}_sample.jsonl`), outBooks);
  // lookup rows of exactly those books, from the PUBLISHED table (falls back to the fixtures_out copy)
  const lutFile = fs.existsSync(path.join(PUB, m.weights)) ? path.join(PUB, m.weights) : path.join(SRC, m.weights);
  const lut = new Map();
  for (const l of fs.readFileSync(lutFile, 'utf8').split('\n')) { if (!l) continue; const c = l.split(','); lut.set(Number(c[0]), l.trim()); }
  source.files[m.weights] = sha(fs.readFileSync(lutFile));
  const rows = kept.map((id) => { const r = lut.get(id); if (!r) throw new Error(`${mode}: book ${id} has no lookup row`); const pay = Number(r.split(',')[2]); if (pay !== byId.get(id).b.payoutMultiplier) throw new Error(`${mode}: book ${id} payout ${byId.get(id).b.payoutMultiplier} != lookup ${pay}`); return r; });
  fs.writeFileSync(path.join(OUT, m.weights), rows.join('\n') + '\n');
  const mc = {}; for (const id of kept) { const k = mockCat(byId.get(id).b); mc[k] = (mc[k] || 0) + 1; }
  summary.push(`${mode}: ${kept.length} books (${(Buffer.byteLength(outBooks) / 1024).toFixed(0)} KB), mock categories ${JSON.stringify(mc)}`);
}
fs.writeFileSync(path.join(OUT, 'index.json'), JSON.stringify(index, null, 4) + '\n');
fs.writeFileSync(path.join(OUT, 'PICKS.md'), picksMd);
for (const f of fs.readdirSync(OUT)) { const p = path.join(OUT, f); if (fs.statSync(p).isFile() && f !== 'SOURCE.json') source.written[f] = sha(fs.readFileSync(p)); }
fs.writeFileSync(path.join(OUT, 'SOURCE.json'), JSON.stringify(source, null, 1) + '\n');
console.log(summary.join('\n'));
